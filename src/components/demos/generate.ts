// Writes the lookup route for a model, the way the LegacyBridge generator
// laid it out: types, a validation schema, the cache check, the legacy call,
// the mapping and the error responses. Sensitive columns are left out of the
// response unless asked for.

import type { Model, ModelField } from './ddl'

export type Lang = 'typescript' | 'python'

export interface Options {
  lang: Lang
  ttl: number // seconds, 0 turns the cache off
  sensitive: boolean
}

const plural = (s: string) => `${s}s`
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)
const snake = (s: string) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`)
const pascal = (s: string) => s[0].toUpperCase() + s.slice(1)

export const exposed = (m: Model, o: Options) => m.fields.filter((f) => o.sensitive || !f.sensitive)

function zod(f: ModelField) {
  let t = { string: 'z.string()', number: 'z.number()', integer: 'z.number().int()', date: 'z.string().date()', datetime: 'z.string().datetime()' }[f.type]
  if (f.maxLength) t += `.max(${f.maxLength})`
  return f.required ? t : `${t}.nullable()`
}

function pydantic(f: ModelField) {
  const t = { string: 'str', number: 'Decimal', integer: 'int', date: 'date', datetime: 'datetime' }[f.type]
  const field = f.maxLength ? ` = Field(max_length=${f.maxLength})` : ''
  return f.required ? `${t}${field}` : `Optional[${t}] = None`
}

// how the key is checked before anything else runs
function keyRule(k: ModelField) {
  if (k.type === 'string' && k.maxLength) return { re: `^\\d{${k.maxLength}}$`, msg: `${k.maxLength} digits` }
  return { re: `^\\d{1,${k.digits ?? 10}}$`, msg: `up to ${k.digits ?? 10} digits` }
}

function typescript(m: Model, o: Options) {
  const fs = exposed(m, o)
  const T = pascal(m.entity)
  const k = m.key
  const rule = keyRule(k)
  const path = `/${kebab(plural(m.entity))}/:${k.name}`
  const cache = o.ttl > 0
  return [
    `// Generated by LegacyBridge AI from ${m.program} (${m.system})`,
    `import { Router } from 'express'`,
    `import { z } from 'zod'`,
    `import { legacy } from './connector'`,
    cache ? `import { redis } from './cache'` : null,
    ``,
    `const ${T} = z.object({`,
    ...fs.map((f) => `  ${f.name}: ${zod(f)}, // ${f.source}`),
    `})`,
    `type ${T} = z.infer<typeof ${T}>`,
    ``,
    `const key = z.string().regex(/${rule.re}/, '${k.name} must be ${rule.msg}')`,
    `const router = Router()`,
    ``,
    `router.get('${path}', async (req, res) => {`,
    `  const id = key.safeParse(req.params.${k.name})`,
    `  if (!id.success) return res.status(400).json({ error: 'Validation Error', details: id.error.issues })`,
    ``,
    ...(cache
      ? [
          `  const hit = await redis.get(\`${m.entity}:\${id.data}\`)`,
          `  if (hit) return res.json({ success: true, data: JSON.parse(hit), metadata: { cached: true } })`,
          ``,
        ]
      : []),
    `  try {`,
    `    const row = await legacy.read('${m.program}', { '${k.source}': id.data }, { timeout: 5000, retries: 2 })`,
    `    if (!row) return res.status(404).json({ error: 'Not Found', message: \`${T} \${id.data} does not exist\` })`,
    `    const data: ${T} = ${T}.parse(map(row))`,
    cache ? `    await redis.setex(\`${m.entity}:\${id.data}\`, ${o.ttl}, JSON.stringify(data))` : null,
    `    res.json({ success: true, data, metadata: { source: '${m.system}', cached: false } })`,
    `  } catch (err) {`,
    `    res.status(500).json({ error: 'Internal Server Error', requestId: req.headers['x-request-id'] })`,
    `  }`,
    `})`,
    ``,
    `// legacy names to API names`,
    `const map = (row: Record<string, string>) => ({`,
    ...fs.map((f) => `  ${f.name}: row['${f.source}'],`),
    `})`,
    ``,
    `export default router`,
  ].filter((l) => l !== null).join('\n')
}

function python(m: Model, o: Options) {
  const fs = exposed(m, o)
  const T = pascal(m.entity)
  const k = m.key
  const rule = keyRule(k)
  const path = `/${kebab(plural(m.entity))}/{${snake(k.name)}}`
  const cache = o.ttl > 0
  const types = new Set(fs.map((f) => f.type))
  return [
    `# Generated by LegacyBridge AI from ${m.program} (${m.system})`,
    types.has('date') || types.has('datetime') ? `from datetime import ${[types.has('date') && 'date', types.has('datetime') && 'datetime'].filter(Boolean).join(', ')}` : null,
    types.has('number') ? 'from decimal import Decimal' : null,
    `from typing import Optional`,
    `from fastapi import APIRouter, HTTPException, Path`,
    `from pydantic import BaseModel, Field`,
    `from connector import legacy`,
    cache ? 'from cache import redis' : null,
    ``,
    `router = APIRouter(prefix="/api/v1")`,
    ``,
    `class ${T}(BaseModel):`,
    ...fs.map((f) => `    ${snake(f.name)}: ${pydantic(f)}  # ${f.source}`),
    ``,
    `@router.get("${path}", response_model=${T})`,
    `async def get_${snake(m.entity)}(${snake(k.name)}: str = Path(pattern=r"${rule.re}")):`,
    ...(cache
      ? [
          `    if hit := await redis.get(f"${m.entity}:{${snake(k.name)}}"):`,
          `        return ${T}.model_validate_json(hit)`,
        ]
      : []),
    `    try:`,
    `        row = await legacy.read("${m.program}", {"${k.source}": ${snake(k.name)}}, timeout=5, retries=2)`,
    `    except TimeoutError:`,
    `        raise HTTPException(500, "Failed to retrieve data from legacy system")`,
    `    if row is None:`,
    `        raise HTTPException(404, f"${T} {${snake(k.name)}} does not exist")`,
    `    data = ${T}(`,
    ...fs.map((f) => `        ${snake(f.name)}=row["${f.source}"],`),
    `    )`,
    cache ? `    await redis.setex(f"${m.entity}:{${snake(k.name)}}", ${o.ttl}, data.model_dump_json())` : null,
    `    return data`,
  ].filter((l) => l !== null).join('\n')
}

export const generate = (m: Model, o: Options) => (o.lang === 'typescript' ? typescript(m, o) : python(m, o))

// the extra routes a model supports, from its key and its indexes
export function routes(m: Model) {
  const base = `/api/v1/${kebab(plural(m.entity))}`
  return [
    { path: `${base}/:${m.key.name}`, why: `by ${m.key.source}` },
    ...(m.search.length ? [{ path: `${base}?${m.search.map((f) => `${f.name}=`).join('&')}`, why: `indexed on ${m.search.map((f) => f.source).join(', ')}` }] : []),
  ]
}
